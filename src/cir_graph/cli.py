"""Build the unified CIR knowledge graph (call graph + CFG + data flow).

Parses one or more Clang IR (.cir) translation units, links them into one
program, and emits a layered knowledge graph:

  Macro  (call graph)     Program, TranslationUnit, FunctionSymbol, Function,
                          GlobalVariable, CALLS
  Meso   (control flow)   BasicBlock, CFG_NEXT {kind, isBackEdge}
  Micro  (data flow)      Operation, Value, DEFINES_VALUE, USES_VALUE, FLOWS_TO
  Bridges                 INVOKES (call op -> callee), FLOWS_TO call_argument /
                          call_return, HAS_PARAMETER, ACCESSES_GLOBAL

Outputs (any subset):
  --database  graph.kuzu          live Kùzu database (transactional load)
  --output    graph.cypher        idempotent Cypher import script
  --json      graph.json          layered JSON for LLM prompts
  --dot       graph.dot           Graphviz visualization

Example:
  cir-graph main.cir helper.cir --program-id demo \\
      --database out/graph.kuzu --output out/graph.cypher \\
      --json out/graph.json --dot out/graph.dot
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
from pathlib import Path
from typing import List

from .exporters import to_dot, to_json
from .linker import build_program
from .models import Program
from .schema import import_statements


def remove_database(path: Path) -> None:
    for target in (path, Path(f"{path}.wal"), Path(f"{path}.lock")):
        if target.is_dir():
            shutil.rmtree(target)
        elif target.exists():
            target.unlink()


def load_kuzu(statements: List[str], database: Path, reset: bool) -> None:
    import kuzu

    if reset:
        remove_database(database)
    database.parent.mkdir(parents=True, exist_ok=True)
    db = kuzu.Database(str(database))
    conn = kuzu.Connection(db)
    conn.execute("BEGIN TRANSACTION")
    try:
        for statement in statements:
            conn.execute(statement)
        conn.execute("COMMIT")
    except Exception:
        conn.execute("ROLLBACK")
        raise
    finally:
        conn.close()
        db.close()


def write_cypher(statements: List[str], path: Path, program: Program) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        handle.write("// Generated by cir-graph: unified call graph + CFG + data flow for Kùzu.\n")
        handle.write(f"// Program: {program.id}. Re-importing replaces this program's nodes only.\n")
        handle.write("// Import: cir-graph-load FILE --database DB  (or paste into Kùzu Explorer)\n\n")
        for statement in statements:
            handle.write(statement + ";\n\n")


def summarize(program: Program) -> str:
    defined = [fn for tu in program.translationUnits for fn in tu.functions]
    blocks = sum(len(fn.blocks) for fn in defined)
    ops = sum(len(fn.operations) for fn in defined)
    values = sum(len(fn.values) for fn in defined)
    flows = sum(len(fn.flows) for fn in defined) + len(program.interFlows)
    cross = sum(1 for c in program.callEdges if c.isCrossTU)
    lines = [
        f"[+] Program '{program.id}': {len(program.translationUnits)} TU(s), "
        f"{len(defined)} defined + {len(program.externFunctions)} external function(s)",
        f"[+] Macro: {len(program.callEdges)} call edge(s) ({cross} cross-TU), "
        f"{len(program.recursionCycles)} recursion cycle(s)",
        f"[+] Meso:  {blocks} basic block(s), {sum(len(fn.cfgEdges) for fn in defined)} CFG edge(s)",
        f"[+] Micro: {ops} operation(s), {values} value(s), {flows} data-flow edge(s)",
    ]
    entries = [fn.demangledName for fn in defined if fn.isEntryPoint]
    dead = [fn.demangledName for fn in defined if fn.isDeadCode]
    lines.append(f"[+] Entry points: {entries or 'none'}")
    if dead:
        lines.append(f"[!] Dead code: {dead}")
    return "\n".join(lines)


def main(argv: List[str] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="cir-graph",
        description="Build the unified call-graph/CFG/data-flow knowledge graph from Clang IR files.")
    parser.add_argument("inputs", nargs="+", help="input .cir files (one per translation unit)")
    parser.add_argument("--database", "-d", type=Path, help="Kùzu database to create or update")
    parser.add_argument("--output", "-o", type=Path, help="Cypher import script to write")
    parser.add_argument("--json", type=Path, help="layered JSON export to write")
    parser.add_argument("--dot", type=Path, help="Graphviz DOT file to write")
    parser.add_argument("--program-id", default=None,
                        help="program identifier (default: name of the first input's directory)")
    parser.add_argument("--name", default=None, help="human readable program name")
    parser.add_argument("--entry", action="append", default=[],
                        help="additional entry point (symbol or demangled name); repeatable")
    parser.add_argument("--reset", action="store_true",
                        help="delete the database before importing (schema changes)")
    parser.add_argument("--batch-size", type=int, default=250, help="rows per UNWIND statement")
    parser.add_argument("--dry-run", action="store_true", help="parse and link only")
    args = parser.parse_args(argv)

    for path in args.inputs:
        if not os.path.isfile(path):
            parser.error(f"input not found: {path}")
    if args.database and not args.dry_run:
        try:
            import kuzu  # noqa: F401
        except ImportError:
            parser.error("the 'kuzu' Python package is required for --database (pip install kuzu)")

    program_id = args.program_id or Path(args.inputs[0]).resolve().parent.name or "program"
    program = build_program(args.inputs, program_id, args.name, args.entry)
    print(summarize(program))
    if args.dry_run:
        return 0

    statements = import_statements(program, args.batch_size) if args.output or args.database else []
    if args.output:
        write_cypher(statements, args.output, program)
        print(f"[+] Cypher script: {args.output} ({len(statements)} statements)")
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        with args.json.open("w", encoding="utf-8") as handle:
            json.dump(to_json(program), handle, indent=2)
            handle.write("\n")
        print(f"[+] JSON export: {args.json}")
    if args.dot:
        args.dot.parent.mkdir(parents=True, exist_ok=True)
        args.dot.write_text(to_dot(program), encoding="utf-8")
        print(f"[+] DOT graph: {args.dot}")
    if args.database:
        load_kuzu(statements, args.database, args.reset)
        print(f"[+] Kùzu database: {args.database}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
